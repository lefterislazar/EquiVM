#!/usr/bin/env python3
"""Generate the Solidity semantics' differential test of the ABI probes: the solc 0.8.37 fixture
(legacy and `--via-ir`) and the calldata of every case of `abi_cases.CALLS`.

    python3 gen_solidity_tests.py <EquiVM checkout>

Writes `Solidity/Test/Fixtures/AbiProbesSolc.lean` and `Solidity/Test/Scenarios/AbiProbes.lean`
from `Solidity/Test/Fixtures/AbiProbes.sol`.
"""

import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "solc_storage_audit"))

from abi_calldata import mutations  # noqa: E402
from abi_cases import CALLS, signature  # noqa: E402
from run_matrix import solc_path  # noqa: E402

VERSION = "0.8.37"
CONTRACTS = ["AbiValue", "AbiMem", "AbiCd", "AbiDecode", "AbiEncode", "AbiRequireError"]
PIPELINES = {"legacy": [], "viaIR": ["--via-ir"]}
UNSUPPORTED = {"fx"}  # function-typed parameters: not modelled by the semantics


def compile_fixture(root):
    sol = root / "Solidity/Test/Fixtures/AbiProbes.sol"
    runtimes = {}
    for pipeline, flags in PIPELINES.items():
        out = subprocess.run([str(solc_path(VERSION)), *flags, "--evm-version", "shanghai", "--bin-runtime", sol.name],
                             cwd=sol.parent, capture_output=True, text=True, check=True).stdout
        for m in re.finditer(r"======= [^:]+:(\w+) =======\nBinary of the runtime part:\n([0-9a-f]+)", out):
            runtimes[(pipeline, m.group(1))] = m.group(2)
    version = subprocess.run([str(solc_path(VERSION)), "--version"], capture_output=True, text=True).stdout
    return runtimes, re.search(r"Version: (\S+?)\.Linux", version).group(1)


def hex_def(name, doc, h):
    chunks = [h[i:i + 96] for i in range(0, len(h), 96)]
    return f"/-- {doc} ({len(h) // 2} bytes). -/\ndef {name} : String :=\n    " + " ++\n    ".join(
        f'"{c}"' for c in chunks) + "\n"


def main():
    root = Path(sys.argv[1])
    runtimes, version = compile_fixture(root)
    defs = []
    for (pipeline, contract), code in sorted(runtimes.items()):
        defs.append(hex_def(f"{contract[0].lower()}{contract[1:]}{pipeline[0].upper()}{pipeline[1:]}RuntimeHex",
                            f"{contract} runtime code, {pipeline}", code))
    fixture = f"""import Solidity.Test.Harness

/-!
# Fixture: `Solidity/Test/Fixtures/AbiProbes.sol` compiled by the local solc

`solc {version} --evm-version shanghai --bin-runtime`, optimizer OFF, with and without `--via-ir`
(`…LegacyRuntimeHex`, `…ViaIRRuntimeHex`).  Generated by `scripts/solc_abi_audit/gen_solidity_tests.py`
(branch `solidity-abi-analysis`).
-/

namespace Solidity.Test.Fixtures

{chr(10).join(defs)}
end Solidity.Test.Fixtures
"""
    (root / "Solidity/Test/Fixtures/AbiProbesSolc.lean").write_text(fixture)

    lines = {c: [] for c in CONTRACTS}
    for n, (probe, fn, types, values) in enumerate(CALLS):
        if fn in UNSUPPORTED:
            continue
        for label, calldata in mutations(signature(fn, types), types, values):
            lines[probe].append(f"{fn}#{n} {label}|{calldata.hex()}")
    case_defs, scenarios = [], []
    for c in CONTRACTS:
        ident = c[0].lower() + c[1:]
        case_defs.append(f'/-- `{c}`: one case per line, `name|calldata`. -/\n'
                         f'def {ident}Cases : String :=\n  "' + "\\n".join(lines[c]) + '"\n')
        for pipeline in PIPELINES:
            p = pipeline[0].upper() + pipeline[1:]
            scenarios.append(f'  scenario "{c}" "{pipeline}" Fixtures.{ident}{p}RuntimeHex {ident}Cases')
    scenario = f"""import Solidity.Test.Harness
import Solidity.Test.Specs.AbiProbes
import Solidity.Test.Fixtures.AbiProbesSolc

/-! # Differential cases: ABI decoding and encoding (generated)

Every call of the ABI probes with valid calldata and with malformed variants, each targeting one
word: dirty value words, offsets and lengths pointing outside the calldata or overflowing,
truncations and trailing data.  Run against solc {VERSION} bytecode of both code generators.
Generated by `scripts/solc_abi_audit/gen_solidity_tests.py` (branch `solidity-abi-analysis`). -/

namespace Solidity.Test.AbiProbes

open Solidity.Test

{chr(10).join(case_defs)}
/-- The cases of one probe contract on one pipeline's runtime code. -/
def scenario (target pipeline runtimeHex cases : String) : Scenario :=
  let code := bytesOfHex runtimeHex
  {{ name := s!"Abi/{{target}}/{{pipeline}}", program := _root_.AbiProbes.SoliditySpec.program, target := target,
    cases := (cases.splitOn "\\n").filterMap fun line =>
      match line.splitOn "|" with
      | [name, hex] => some {{ name := name, code := code, calldata := bytesOfHex hex }}
      | _ => none }}

def scenarios : List Scenario :=
  [{(","+chr(10)).join(scenarios).lstrip()} ]

end Solidity.Test.AbiProbes
"""
    (root / "Solidity/Test/Scenarios/AbiProbes.lean").write_text(scenario)
    print(f"solc {version}: {len(runtimes)} runtimes, {sum(len(v) for v in lines.values())} cases")


if __name__ == "__main__":
    main()
